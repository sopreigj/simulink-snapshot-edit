%% ---------- 多行字符串 -> MATLAB cell 字面量（供 strjoin 还原真换行）----------
%  为什么不能直接赋双引号字符串：Stateflow 的 Script setter 收到含 \n 的
%  string 时会把它当**字面两字符**，函数体因此挤成一行 → 编译失败。
%  实测可用写法：strjoin({'行1','行2'}, sprintf('\n'))（每行一个 char 字面量）。
function s = mval_lines(v)
  if ~ischar(v)
    s = mval(v); return;
  end
  v = strrep(v, sprintf('\n'), sprintf('\n'));
  L = strsplit(v, sprintf('\n'));
  parts = cellfun(@(x) mval(x), L, 'UniformOutput', false);
  s = ['{', strjoin(parts, ', '), '}'];
end

%% ---------- value -> MATLAB literal (multiline/quote safe, 17-digit round-trip) ----------
function s = mval(v)
  if ischar(v)
    if contains(v, sprintf('\n')) || contains(v, '"')
      % 顺序要紧：先把**真换行**换成占位符，再转义原有的反斜杠与引号，
      % 最后把占位符还原成字面 \n。否则先转义反斜杠会把后面生成的 \n
      % 也变成 \\n——换行就变成了字面两字符（实测：Script 挤成一行 → 编译失败）。
      w = strrep(v, sprintf('\n'), char(1));
      w = strrep(w, '\', '\\');
      w = strrep(w, '"', '\"');
      w = strrep(w, char(1), '\n');
      s = ['"' w '"'];
    else
      s = ['''' strrep(v, '''', '''''') ''''];
    end
  elseif islogical(v)
    if v, s = '''on'''; else, s = '''off'''; end
  elseif isnumeric(v)
    if isscalar(v), s = num2str(v, 17); else, s = mat2str(v, 17); end
  else
    s = '''''';
  end
end

%% ---------- 库路径（add_block 的 src）专用转义 ----------
% mval 的双引号串把 char(10) 写成字面 \n，但 MATLAB 双引号串**不解释** \n
% （2026-10-29 实测：double(char("aa\nbb"))=[97 97 92 110 98 98]），故重建时
% add_block 拿到的是字面反斜杠+n 而非真换行，含换行的库路径（ee_lib 物理块，
% T28/T33）必败。本函数把含 char(10) 的 src 写成 ['段', char(10), '段'] 拼接，
% 重建时恢复真换行。单引号串内反斜杠是字面、无需转义；单引号转成 ''。
% 无换行时与 mval 完全等价。
function s = msrc(src)
  if ~ischar(src) || ~any(double(src) == 10)
    s = mval(src);   % 无换行走原路（注意此处必须调 mval，replace_all 曾误伤成递归）
    return;
  end
  parts = strsplit(src, char(10));
  esc = cellfun(@(p) ['''' strrep(p, '''', '''''') ''''], parts, 'UniformOutput', false);
  % sep 不含引号：esc 元素已自带前后引号，sep 只负责逗号与 char(10)
  % （首版误在 sep 两端加 char(39)，与 esc 自带引号重复，快照里出现 ''）
  sep = ', char(10), ';
  s = ['[' strjoin(esc, sep) ']'];
end


