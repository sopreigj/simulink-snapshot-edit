%% ---------- 变体容器自动端口判定 ----------
%  变体子系统里 Simulink 会按分支自动生成 In1/Out1；重建为普通 Subsystem 时
%  这些端口由 Simulink 重新自动生成，不能再手工建一遍（否则"无法添加名为 …"）。
function tf = isauto_variant_port(blk, container)
  tf = false;
  try
    % 自动端口块的端口号来自分支，自身没有用户可编辑的 Port 设定；
    % 判据：块名符合 In<N>/Out<N> 且其父容器是变体容器。
    nm = get_param(blk, 'Name');
    if ~isempty(regexp(nm, '^(In|Out)\d+$', 'once'))
      tf = strcmp(get_param(blk, 'Parent'), container);
    end
  catch
  end
end

%% ---------- 绝对路径判定（Windows 盘符 / UNC / POSIX 根）----------
function tf = isabs_path(p)
  if isempty(p), tf = false; return; end
  tf = ~isempty(regexp(p, '^[A-Za-z]:[\\/]', 'once')) || ...
       ~isempty(regexp(p, '^\\\\', 'once')) || startsWith(p, '/');
end

%% ---------- 真 S-Function 的 .m 实现随快照走（自包含）----------
%  MATLAB Function 块不算：它的实现就在 chart 脚本里，已随块导出。
function sfFiles = collect_sfun_files(mdl, outDir)
  sfFiles = {};
  try
    blks = find_system(mdl, 'LookUnderMasks', 'all', 'FollowLinks', 'off', 'Type', 'block');
  catch
    return;
  end
  modelDir = '';
  try, modelDir = get_param(mdl, 'Path'); catch, end
  fnDir = fullfile(outDir, 'functions');
  for i = 1:numel(blks)
    try
      if ~strcmp(get_param(blks{i}, 'BlockType'), 'S-Function'), continue; end
      fn = get_param(blks{i}, 'FunctionName');
      if isempty(fn) || contains(fn, '|') || strcmp(fn, 'sf_sfun'), continue; end
      p = which(fn);
      if (isempty(p) || ~endsWith(lower(p), '.m')) && ~isempty(modelDir)
        cand = fullfile(modelDir, [fn '.m']);
        if exist(cand, 'file'), p = cand; end
      end
      if isempty(p) || ~endsWith(lower(p), '.m'), continue; end
      if ~isfolder(fnDir), mkdir(fnDir); end
      [~, base] = fileparts(p);
      dst = fullfile(fnDir, [base '.m']);
      if ~exist(dst, 'file'), copyfile(p, dst); end
      sfFiles{end+1} = base; %#ok<AGROW>
    catch
    end
  end
  sfFiles = unique(sfFiles);
end

