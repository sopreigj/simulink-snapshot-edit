%% ---------- chart 接口核对（只核对不修改）----------
%  实测结论（T8/T9，R2023b）：
%  用 strjoin({'行','行'}, sprintf('\n')) 把真换行的 char 数组写进
%  rtc.Script，Stateflow 会正确解析函数签名并自动给出正确接口
%  （实测 SubGroup1：{x:Input, y:Output}，函数体完整，编译通过）。
%  真正的坑是写法：char("...\n...") 会把多行字符串变成字符矩阵，
%  Stateflow 只识别首行 → 接口被推断成 {u:Input, y:Output} 或多出输入。
%  所以这里只做核对：接口与导出时不一致就打印警告，不擅自删除 Data
%  （删除会把函数体一并清掉）。
function emit_chart_restore(fid, srcPath, destRel, sc)
  [names, scopes] = get_chart_data(srcPath);
  if isempty(names), return; end
  fprintf(fid, '  try\n');
  fprintf(fid, '    rcd = get_param(m, ''Object'').find(''-isa'', ''Stateflow.EMChart'', ''-and'', ''Path'', [m ''/%s'']);\n', destRel);
  fprintf(fid, '    if ~isempty(rcd)\n');
  fprintf(fid, '      rdd = rcd.find(''-isa'', ''Stateflow.Data'');\n');
  fprintf(fid, '      rnm = cellfun(@(x) x.Name, rdd, ''UniformOutput'', false);\n');
  fprintf(fid, '      if ~isequal(sort(rnm), sort({%s}))\n', ...
    strjoin(cellfun(@(x) ['''' x ''''], names, 'UniformOutput', false), ', '));
  fprintf(fid, '        warning(''[snp_export] chart %s 接口与原件不一致：得到 %s'');\n', destRel, ...
    'strjoin(rnm, ",")');
  fprintf(fid, '      end\n');
  fprintf(fid, '    end\n');
  fprintf(fid, '  catch\n');
  fprintf(fid, '  end\n');
end

%% ---------- chart 的 Data 接口（输入/输出名与 Scope）----------
%  回灌 Script 后 Stateflow 会把函数体里的自由变量（mod/pi/ny…）当成
%  **新增输入**，接口一变，父级连线接错 → 模型编译失败。故必须把接口
%  恢复成导出时的原样。
function [names, scopes] = get_chart_data(b)
  names = {}; scopes = {};
