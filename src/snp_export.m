%% snp_export.m — 模型 → 自足 M 快照导出器（simulink-snapshot-edit）
%
%  把一个已排版好的 Simulink 模型导出为"自足 M 快照"：运行一次即重建
%  完全一样的模型（全部块/全部参数/显示尺寸 Position/布线折线/注解/
%  求解器配置/Model Workspace 变量）。之后只需编辑快照中对应块的若干行
%  即可局部修改模型——其他块与相对位置原样保留。
%
%  用法
%    opts.LibDir    = 'path/to/lib/blocks';  % 库 .slx 搜索目录（实例源解析）
%    opts.AliasMap  = {'Prefix','Subsys'; ...};  % 实例名→库模块名缩写表
%    opts.OutDir    = 'out';                 % 快照输出目录（默认当前目录）
%    opts.ExtraHeader = {'addpath(...);'};   % 生成代码头部附加行（可选）
%    snp_export('MyModel', opts);
%
%  实例源解析（三级，自动）：
%    ① 子系统内 FP_* 指纹注解；② 块名（去尾数字）匹配 LibDir/*.slx；
%    ③ 别名表。MATLAB Function 块按 Script 参数复制。
%
%  保真承诺：Position 原样写入；线按源端口扇出归组 + Points 恢复精确折线；
%  数值 17 位有效数字（double 精确往返）；存临时名再 movefile。
%  目标版本 R2023b（version 断言在函数体内）。

function snp_export(mdl, opts)
  if nargin < 2, opts = struct; end
  if ~isfield(opts, 'LibDir'),      opts.LibDir = ''; end
  if ~isfield(opts, 'AliasMap'),    opts.AliasMap = cell(0,2); end
  if ~isfield(opts, 'OutDir'),      opts.OutDir = pwd; end
  if ~isfield(opts, 'ExtraHeader'), opts.ExtraHeader = {}; end
  % InlineMasks=true 时把 masked 子系统**展开成普通子系统**导出其内部结构
  % （库模型自身就是 masked 子系统——没有它就无法导出"子系统内部的代码"）
  if ~isfield(opts, 'InlineMasks'), opts.InlineMasks = false; end
  % LibRel / SaveRel：相对**快照文件所在目录**的库目录 / 目标目录（可移植）
  if ~isfield(opts, 'LibRel'),  opts.LibRel = ''; end
  if ~isfield(opts, 'SaveRel'), opts.SaveRel = ''; end
  % 目标版本 R2023b。多版本兼容测试时放行：opts.AllowUntestedVersion=true
  % 或环境变量 SNP_ALLOW_UNTESTED=1（verify_multiver.m 用它让下游套件
  % verify_rebuild_all/verify_behavior/... 里的导出调用一并放行）。
  allowUn = (isfield(opts, 'AllowUntestedVersion') && opts.AllowUntestedVersion) ...
    || strcmp(getenv('SNP_ALLOW_UNTESTED'), '1');
  if ~allowUn
    assert(strcmp(version('-release'), '2023b'), '本工具当前仅验证于 R2023b（多版本测试请设 opts.AllowUntestedVersion=true）');
  else
    fprintf(2, 'warning: snp_export 在 %s 上运行，未验证版本（AllowUntestedVersion=true）\n', version('-release'));
  end
  % 导出读的是内存中的模型：仿真运行中导出的快照可能反映未生效的
  % 中间状态（仿真中改参数停止后才生效）——提醒但不阻断
  snp_runtime_warn(mdl, 'read');
  if ~bdIsLoaded(mdl), load_system(mdl); end
  if ~isempty(opts.LibDir) && isfolder(opts.LibDir)
    addpath(opts.LibDir);
    d = dir(fullfile(opts.LibDir, '*.slx'));
    libNames = erase({d.name}, '.slx');
  else
    libNames = {};
  end
  outPath = fullfile(opts.OutDir, ['snapshot_' mdl '.m']);

  fid = fopen(outPath, 'w');
  assert(fid > 0, 'cannot write %s', outPath);
  fprintf(fid, 'function snapshot_%s()\n', mdl);
  fprintf(fid, ['%% Self-contained snapshot generated by simulink-snapshot-edit.\n' ...
                '%% Run once to rebuild %s.slx exactly (blocks/params/positions/routing).\n' ...
                '%% Local-edit workflow: edit only the lines of the block you need.\n'], mdl);
  for i = 1:numel(opts.ExtraHeader)
    fprintf(fid, '  %s\n', opts.ExtraHeader{i});
  end
  fprintf(fid, '  if bdIsLoaded(''%s''), close_system(''%s'', 0); end\n', mdl, mdl);
  % 库模型必须按 Library 重建：new_system(name) 出普通模型，库块的引用实例
  % add_block 会得内联副本失链（玩具库 ToyLib 实测，Z3 报 bug 3）
  bdType = '';
  try, bdType = get_param(mdl, 'BlockDiagramType'); catch, end
  if strcmp(bdType, 'library')   % MATLAB 返回小写 'library'（实测，非 'Library'）
    fprintf(fid, '  new_system(''%s'', ''Library'');\n', mdl);
  else
    fprintf(fid, '  new_system(''%s'');\n', mdl);
  end
  fprintf(fid, '  m = ''%s'';\n', mdl);   % 字面模型名，绝不用 bdroot：
  % head 的 load_system(库) 会把 bdroot 切到库（实测 R2023b），
  % 此时 m=get_param(bdroot,'Name') 取到库名 → 后续 add_block
  % 全部写进锁定的库（ToyLibRef 自足重建失败的真因，T64）

  %% solver/config/model params（与 new_system 默认模型逐项 diff，非默认才写入）+ 回调
  modelParams = {'SolverType','SolverName','FixedStep','StartTime','StopTime', ...
    'DefaultBlockFontName','DefaultBlockFontSize','ScreenColor','Description'};
  cfgExtra = {'SaveTime','TimeSaveName','SaveOutput','OutputSaveName', ...
    'SaveState','StateSaveName','SaveFinalState','SaveFormat', ...
    'SaveCompleteFinalSimState','DeviceType'};
  callbacks = {'PreLoadFcn','InitFcn','StartFcn','StopFcn','CloseFcn','SaveFcn','DeleteFcn'};
  defM = 'snp_defprobe';
  if bdIsLoaded(defM), close_system(defM, 0); end
  new_system(defM);
  fprintf(fid, '\n  %% ---- solver / config / model params ----\n');
  for i = 1:numel(modelParams)
    try
      v = get_param(mdl, modelParams{i}); vd = get_param(defM, modelParams{i});
      if ~isequal(v, vd)
        fprintf(fid, '  set_param(m, ''%s'', %s);\n', modelParams{i}, mval(v));
      end
    catch
    end
  end
  for i = 1:numel(cfgExtra)
    try
      v = get_param(mdl, cfgExtra{i}); vd = get_param(defM, cfgExtra{i});
      if ~isequal(v, vd)
        fprintf(fid, '  set_param(m, ''%s'', %s);\n', cfgExtra{i}, mval(v));
      end
    catch
    end
  end
  close_system(defM, 0);  % 探针模型只读默认值，不落盘（落盘会污染 cwd 并触发 shadowing 警告）
  fprintf(fid, '\n  %% ---- callbacks ----\n');
  for i = 1:numel(callbacks)
    try
      v = get_param(mdl, callbacks{i});
      if ischar(v) && ~isempty(strtrim(v))
        fprintf(fid, '  set_param(m, ''%s'', %s);\n', callbacks{i}, mval(v));
      end
    catch
    end
  end

  %% Model Workspace variables
  fprintf(fid, '\n  %% ---- Model Workspace variables ----\n');
  % 库（.slx library）的 ModelWorkspace 不支持 whos（抛出"此类型的变量不支持使用
  % 点索引"），库本来也没有模型工作区变量——取不到就当空，不能让导出整个崩掉。
  vars = [];
  try
    ws = get_param(mdl, 'ModelWorkspace');
    vars = ws.whos;
  catch
    vars = [];
  end
  for i = 1:numel(vars)
    try
      fprintf(fid, '  assignin(get_param(m, ''ModelWorkspace''), ''%s'', %s);\n', ...
              vars(i).name, mval(ws.getVariable(vars(i).name)));
    catch
    end
  end

  %% blocks
  fprintf(fid, '\n  %% ---- blocks (positions & full parameters preserved) ----\n');
  blks = find_system(mdl, 'LookUnderMasks', 'none', 'FollowLinks', 'off', 'Type', 'block');
  blks = setdiff(blks, {mdl});
  depth = cellfun(@(p) numel(strfind(p, '/')), blks);
  [~, ord] = sort(depth, 'ascend');
  blks = blks(ord);
  libsNeeded = {};
  libFiles = {};
  chartLines = {};
  nSkip = 0;
  expanded = {};   % 已由 expand_masked 处理过的容器（其内部块不再重复导出）
  innerEmitted = {};  % 内部块+内部线已在 blocks 节 emit 的容器——
                      % lines 节须跳过它们，否则内部线重复 emit，
                      % 重建报"目标端口已有信号线连接"（玩具库 T56 场景重现）
  for i = 1:numel(blks)
    b = blks{i};
    % 容器已展开 → 其内部块由 expand_masked 导出过，这里跳过（否则重复建块）
    if any(cellfun(@(p) startsWith(b, [p '/']), expanded))
      continue;
    end
    rel = strrep(b, [mdl '/'], '');
    bt = get_param(b, 'BlockType');
    try, rb = get_param(b, 'ReferenceBlock'); catch, rb = ''; end
    src = '';
    isMasked = false;
    try, isMasked = strcmp(get_param(b, 'Mask'), 'on'); catch, end
    % **无库链接的子系统一律展开**导出其内部：断链副本（忠实化模型里的
    % SubSysA/LeafB 等，ReferenceBlock 为空）、库模型自身的根、以及
    % 普通子系统（如 SubGroup1）。跳过它会让引用它的顶层线 add_line 报
    % "Simulink 对象名称无效: 'Plant/8'"。有库链接的保持链接——其内容由
    % 该库自己的快照负责。
    % **独立 chart 除外**：chart 块是状态机不是块树，展开会导成
    % sf_sfun 内联副本（失真）；交给后面的 chart_of 检测走 sflib/Chart +
    % 结构化导出（玩具 ToyChart 实测）。
    if opts.InlineMasks && isempty(rb) && strcmp(bt, 'SubSystem') && isempty(chart_of(b))
      [libsNeeded, libFiles] = expand_masked(fid, b, rel, mdl, libNames, opts, libsNeeded, libFiles);
      expanded{end+1} = b; %#ok<AGROW>
      innerEmitted{end+1} = b; %#ok<AGROW>
      continue;
    end
    if ~isempty(rb)
      src = rb;
      % 引用实例的库须在 head 注册 load_system，否则重建时库未加载、
      % rb 指向的实例得内联副本失链（玩具库实测，Z3 报 bug 3b）。
      % 库名 = rb 首段；仅当 LibDir 有该库且不是被导出的模型自身时注册。
      libName = regexp(rb, '^([^/]+)', 'match', 'once');
      if ~isempty(libName) && ~strcmp(libName, mdl) && any(strcmp(libNames, libName))
        libsNeeded{end+1} = libName; %#ok<AGROW>
        libFiles{end+1} = [libName '.slx']; %#ok<AGROW>
      end
    else
      src = snp_block_source(bt);
      if isempty(src) && strcmp(bt, 'SubSystem')
        mod = libmod_of(b, libNames, opts.AliasMap);
        if ~isempty(mod) && strcmp(mod, mdl)
          mod = '';   % 库自身（库模型的根内容）不得自引用
        end
        if ~isempty(mod)
          src = [mod '/' mod];
          libsNeeded{end+1} = mod; %#ok<AGROW>
            libFiles{end+1} = [mod '.slx']; %#ok<AGROW>
        else
          % MATLAB Function 块（内容在 Stateflow chart 的 Script）
          if ~isempty(get_chart_script(b))
            src = 'simulink/User-Defined Functions/MATLAB Function';
          end
        end
      end
      % 真 S-Function（自定义 .m 实现，不是 MATLAB Function）：按 S-Function 块
      % 导出，FunctionName/Parameters 走 emit_block_params；.m 文件由
      % collect_sfun_files 复制到 <快照目录>/functions 并在 head 里 addpath。
      if isempty(src) && strcmp(bt, 'S-Function') && isempty(get_chart_script(b))
        src = 'simulink/User-Defined Functions/S-Function';
      end
      % 独立 Stateflow chart（sflib/Chart，BlockType=SubSystem，无 Script）：
      % 内容是图形化状态机，不是块树——由 emit_chart_content 结构化导出（T42/T44）
      if isempty(src) && ~isempty(chart_of(b))
        src = 'sflib/Chart';
      end
      % 无库源的裸 SubSystem 兜底（X4 实测缺陷：人新建的子系统不属于任何库，
      % libmod_of 找不到 → src 为空 → skip → 容器行不回流，pull 后快照不可重建）。
      % built-in/SubSystem 建空容器，内部块照常按独立块导出。
      if isempty(src) && strcmp(bt, 'SubSystem')
        src = 'built-in/SubSystem';
      end
    end
    if isempty(src)
      % masked 子系统展开导出（库模型自身 / opts.InlineMasks）
      isMasked = false;
      try, isMasked = strcmp(get_param(b, 'Mask'), 'on'); catch, end
      if opts.InlineMasks && isMasked
        [libsNeeded, libFiles] = expand_masked(fid, b, rel, mdl, libNames, opts, libsNeeded, libFiles);
        continue;
      end
      fprintf(2, '[snp_export skip] %s (BlockType=%s)\n', rel, bt);
      nSkip = nSkip + 1;
      continue;
    end
    if strcmp(bt, 'Inport') || strcmp(bt, 'Outport')
      % 端口块只写端口号：In1/Out1 不接受 OutputFunctionCall / BusOutputAsStruct
      % 等非端口参数（变体容器的自动端口尤其明显）
      pnum = str2double(get_param(b, 'Port'));
      if isnan(pnum) || pnum < 1, pnum = 1; end
fprintf(fid, '  add_block(%s, [m ''/%s''], ''Position'', %s, ''Port'', ''%d'');\n', ...
        msrc(src), rel, mat2str(get_param(b, 'Position')), pnum);
      continue;
    end
    % 库路径可能含换行（find_system 用 <NL> 分隔层级），必须经 mval 转义，
    % 否则写进快照会截断文件（"字符向量未正常终止"）
fprintf(fid, '  add_block(%s, [m ''/%s''], ''Position'', %s', msrc(src), rel, mat2str(get_param(b, 'Position')));
    emit_block_params(fid, b);
    fprintf(fid, ');\n');
    % 无库链接的 masked SubSystem：mask 参数随块重放（H 矩阵类 7 缺口）。
    % 有 rb 的 masked 副本由库侧负责 mask 内容；裸 mask 只建容器会丢 Kp/Ki。
    % 用 Mask.create+addParameter（set_param 的 MaskPrompts 不能凭空造参数，
    % R2023b 实测报"没有为 'Kp' 的参数"）。
    if strcmp(bt, 'SubSystem') && isMasked && isempty(rb)
      emit_mask_create(fid, b, rel);
      % LookUnderMasks='none' 遮蔽了 masked 内部块，主循环列不到——
      % 补导出直接子级（端口块由容器自生，跳过——与 T39 同源）
      [libsNeeded, libFiles] = emit_inner_bare_masked(fid, b, rel, mdl, ...
        libNames, opts, libsNeeded, libFiles);
      innerEmitted{end+1} = b; %#ok<AGROW>
    end
    sc = get_chart_script(b);
    if ~isempty(sc)
      fprintf(fid, '  rtc = get_param(m, ''Object'').find(''-isa'', ''Stateflow.EMChart'', ''-and'', ''Path'', [m ''/%s'']);\n', rel);
      fprintf(fid, '  rtc.Script = strjoin(%s, sprintf(''\\n''));\n', mval_lines(sc));
      emit_chart_restore(fid, b, rel, sc);
    end
    % 独立 Stateflow chart：结构化导出状态/转移（T42/T44——chart 无 Script，
    % 内容是图形化状态机，逐个 Stateflow.State/Transition 重建；
    % idx 用于快照内变量名唯一，避免多 chart 冲突）
    chObj = chart_of(b);
    if ~isempty(chObj)
      emit_chart_content(fid, chObj, rel);
    end
  end
  % 函数块端口随 Script 适配：先 try-update 再画线（编译可能因欠定输入失败，
  % 但输出端口已在失败前适配；'SMO/2' 类无效端口错由此消解）
  fprintf(fid, '  try, set_param(m, ''SimulationCommand'', ''update''); catch, end\n');
  if nSkip > 0
    fprintf(2, '[snp_export WARNING] %s: %d blocks skipped — snapshot INCOMPLETE\n', mdl, nSkip);
  end

  %% lines (fan-out grouped by source port; exact polyline preserved)
  fprintf(fid, '\n  %% ---- lines ----\n');
  lines = find_system(mdl, 'FindAll', 'on', 'LookUnderMasks', 'none', 'FollowLinks', 'off', 'Type', 'line');
  groups = struct('srcName', {}, 'srcPort', {}, 'parentRel', {}, 'dstName', {}, 'dstPort', {}, 'mainPts', {}, 'sigName', {});
  for i = 1:numel(lines)
    lh = lines(i);
    try
      srcH = get_param(lh, 'SrcPortHandle');
      if srcH <= 0, continue; end
      % 物理端口（Simscape）没有可用的端口号，按端口号写会接错口/报错——
      % 这类连接由后面的 snp_phys_connections 按 LConn/RConn 名单独导出
      try
        if strcmp(get_param(srcH, 'PortType'), 'connection'), continue; end
      catch
      end
      dstH = get_param(lh, 'DstPortHandle');
      dstH = dstH(dstH > 0);
      if isempty(dstH), continue; end
      % 线所属系统：顶层=模型（emit m），内部=父容器（emit [m '/blk']）——
      % 内部线的 add_line 容器必须是该子系统本身，否则重建报
      % "Simulink 对象名称无效"（T56）。同分组键加 parentRel 也是为避免
      % 不同容器下的同名块（blk1/g1 与 blk2/g1）被并成一组而接错线。
      % R2023b 实测：line 的 Parent 直接返回完整路径 char（不是句柄），
      % 且 SubSystem 块没有 'Path' 参数——按句柄取 Path 必抛错回落到顶层。
      parentSys = get_param(lh, 'Parent');
      if ischar(parentSys) || isstring(parentSys)
        parent = char(parentSys);
      else
        parent = char(getfullname(parentSys));   % 句柄形态
      end
      if strcmp(parent, mdl) || isempty(parent)
        parentRel = 'm';
      else
        parentRel = sprintf('[m ''/%s'']', strrep(parent, [mdl '/'], ''));
      end
      % 容器的内部块+内部线已在 blocks 节 emit（expand_masked /
      % emit_inner_bare_masked）→ lines 节跳过，否则重复连同一端口
      if any(strcmp(innerEmitted, parent)), continue; end
      g = find(strcmp({groups.srcName}, get_param(get_param(lh, 'SrcBlockHandle'), 'Name')) & ...
               [groups.srcPort] == get_param(srcH, 'PortNumber') & ...
               strcmp({groups.parentRel}, parentRel), 1);
      if isempty(g)
        g = numel(groups) + 1;
        groups(g).srcName = get_param(get_param(lh, 'SrcBlockHandle'), 'Name');
        groups(g).srcPort = get_param(srcH, 'PortNumber');
        groups(g).parentRel = parentRel;
        groups(g).dstName = {}; groups(g).dstPort = []; groups(g).mainPts = []; groups(g).sigName = '';
        try
          sn = get_param(lh, 'Name');
          if ischar(sn), groups(g).sigName = sn; end
        catch
        end
      end
      pts = get_param(lh, 'Points');
      if numel(pts) > numel(groups(g).mainPts), groups(g).mainPts = pts; end
      for k = 1:numel(dstH)
        dn = get_param(get_param(dstH(k), 'Parent'), 'Name');
        if any(strcmp(groups(g).dstName, dn)) && any(groups(g).dstPort == get_param(dstH(k), 'PortNumber'))
          continue;
        end
        groups(g).dstName{end+1} = dn; %#ok<AGROW>
        groups(g).dstPort(end+1) = get_param(dstH(k), 'PortNumber'); %#ok<AGROW>
      end
    catch
    end
  end
  nLine = 0;
  for g = 1:numel(groups)
    for k = 1:numel(groups(g).dstName)
      fprintf(fid, '  lnH = add_line(%s, ''%s/%d'', ''%s/%d'', ''autorouting'', ''off'');\n', ...
              groups(g).parentRel, groups(g).srcName, groups(g).srcPort, ...
              groups(g).dstName{k}, groups(g).dstPort(k));
      if k == 1 && ~isempty(groups(g).mainPts)
        fprintf(fid, '  try, set_param(lnH, ''Points'', %s); catch, end\n', mat2str(groups(g).mainPts));
      end
      % 信号标签（线 Name）：主线设一次即随扇出传播
      if k == 1 && ~isempty(groups(g).sigName)
        fprintf(fid, '  try, set_param(lnH, ''Name'', %s); catch, end\n', mval(groups(g).sigName));
      end
      nLine = nLine + 1;
    end
  end

  %% physical (Simscape) connections —— 端口名 LConn<N>/RConn<N>，不走端口号
  %  每个物理网络连一棵星形生成树：一个端口只能作为目标连一次，按完全图逐对
  %  连会报"第二个端口已有信号线连接"（T14）
  cons = snp_phys_connections(mdl);
  if ~isempty(cons)
    fprintf(fid, '\n  %% ---- physical (Simscape) connections ----\n');
    for i = 1:numel(cons)
      net = cons{i};
      for q = 2:numel(net)
        fprintf(fid, '  add_line(m, ''%s'', ''%s'');\n', net{1}, net{q});
      end
    end
  end

  %% annotations (top level only; library-internal notes belong to the library)
  fprintf(fid, '\n  %% ---- annotations (top level) ----\n');
  anns = find_system(mdl, 'FindAll', 'on', 'SearchDepth', 1, 'Type', 'annotation');
  for i = 1:numel(anns)
    try
      if ~strcmp(get_param(anns(i), 'Parent'), mdl), continue; end
      fprintf(fid, '  nb = add_block(''built-in/Note'', [m ''/snp_ann_%d'']);\n', i);
      fprintf(fid, '  set_param(nb, ''Name'', %s);\n', mval(get_param(anns(i), 'Name')));
      fprintf(fid, '  try, set_param(nb, ''FontSize'', ''%s''); catch, end\n', get_param(anns(i), 'FontSize'));
      apos = get_param(anns(i), 'Position');
      fprintf(fid, '  dp = get_param(nb, ''Position'');\n');
      fprintf(fid, '  set_param(nb, ''Position'', [%d %d %d %d]);\n', apos(1), apos(2), ...
        apos(1) + max(1, apos(3)-apos(1)), apos(2) + max(1, apos(4)-apos(2)));
    catch
    end
  end

  % save under temp name then move (avoids "model already open" clash)
  % SaveRel: 目标目录相对**本快照文件所在目录**（可移植，不含本机绝对路径）
  if isempty(opts.SaveRel)
    fprintf(fid, '\n  try, bdclose(''%s_tmp_save''); catch, end\n', mdl);
    fprintf(fid, '  if isfile(''%s_tmp_save.slx''), delete(''%s_tmp_save.slx''); end\n', mdl, mdl);
    fprintf(fid, '  save_system(m, ''%s_tmp_save.slx'');\n', mdl);
    fprintf(fid, '  close_system(m, 0);\n');
    fprintf(fid, '  movefile(''%s_tmp_save.slx'', ''%s.slx'', ''f'');\n', mdl, mdl);
  else
    fprintf(fid, '\n  snpDir = fileparts(mfilename(''fullpath''));\n');
    if isabs_path(opts.SaveRel)
      % 绝对路径：fullfile 不会吸收盘符，必须直接赋值
      fprintf(fid, '  snpOut = ''%s'';\n', opts.SaveRel);
    else
      fprintf(fid, '  snpOut = fullfile(snpDir, ''%s'');\n', opts.SaveRel);
    end
    fprintf(fid, '  try, bdclose(''%s_tmp_save''); catch, end\n', mdl);
    fprintf(fid, '  if ~isfolder(snpOut), mkdir(snpOut); end\n');
    fprintf(fid, '  if isfile(fullfile(snpOut, ''%s_tmp_save.slx'')), delete(fullfile(snpOut, ''%s_tmp_save.slx'')); end\n', mdl, mdl);
    fprintf(fid, '  save_system(m, fullfile(snpOut, ''%s_tmp_save.slx''));\n', mdl);
    fprintf(fid, '  close_system(m, 0);\n');
    fprintf(fid, '  movefile(fullfile(snpOut, ''%s_tmp_save.slx''), fullfile(snpOut, ''%s.slx''), ''f'');\n', mdl, mdl);
  end
  fprintf(fid, 'end\n\n');  fclose(fid);

  % S-Function 的 .m 实现随快照走（自包含）：扫描模型里所有真 S-Function
  % 块，把其 .m 文件复制到 <快照目录>/functions/，head 里 addpath。
  sfFiles = collect_sfun_files(mdl, opts.OutDir);

  if ~isempty(libsNeeded) || ~isempty(sfFiles)
    if ~isempty(libsNeeded)
      [libsNeeded, ui] = unique(libsNeeded);
      libFiles = libFiles(ui);
    end
    head = {};
    for i = 1:numel(libFiles)
      if isempty(opts.LibRel)
        head{end+1} = sprintf('  if ~bdIsLoaded(''%s''), load_system(''%s''); end', ...
          stripExt(libFiles{i}), libFiles{i}); %#ok<AGROW>
      elseif isabs_path(opts.LibRel)
        head{end+1} = sprintf('  if ~bdIsLoaded(''%s''), load_system(fullfile(''%s'', ''%s'')); end', ...
          stripExt(libFiles{i}), opts.LibRel, libFiles{i}); %#ok<AGROW>
      else
        head{end+1} = sprintf('  if ~bdIsLoaded(''%s''), load_system(fullfile(fileparts(mfilename(''fullpath'')), ''%s'', ''%s'')); end', ...
          stripExt(libFiles{i}), opts.LibRel, libFiles{i}); %#ok<AGROW>
      end
    end
    if ~isempty(sfFiles)
      % S-Function 的 .m 实现随快照走（自包含）：快照目录下的 functions/
      head{end+1} = sprintf('  addpath(fullfile(fileparts(mfilename(''fullpath'')), ''functions''));');
    end
    txt = fileread(outPath);
    % head 插在 new_system 之前（库在重建前就绪）；锚点用 m 赋值行——
    % m 已字面化为模型名（T64），用 '\n  m = ''<mdl>'';' 定位
    anchor = sprintf('\n  m = ''%s'';', mdl);
    txt = strrep(txt, anchor, [anchor sprintf('\n%s', head{:})]);
    fid2 = fopen(outPath, 'w'); fwrite(fid2, txt); fclose(fid2);
  end
        end

%% ---------- block parameter set ----------
function emit_block_params(fid, b)
  try, dps = get_param(b, 'DialogParameters'); catch, return; end
  if isempty(dps), return; end
  % ModelReference（Model 块）：只写 ModelName——其余参数（PortDiscreteRates、
  % CachedPortDiscreteRates、ScheduleRates*、ShowModel*Ports…）由 Simulink 在
  % 引用模型加载后自行推导，写入反而报"设置无效"。
  try
    if strcmp(get_param(b, 'BlockType'), 'ModelReference')
      mn = get_param(b, 'ModelName');
      if ischar(mn) && ~isempty(mn)
        fprintf(fid, ', ''ModelName'', %s', mval(mn));
      end
      return;
    end
  catch
  end
  names = fieldnames(dps);
  % masked 块的 mask 参数名集合。**只在无 rb 的裸 masked 块跳过**（走
  % emit_mask_create 重建）；有 rb 的库链接实例（slope/start 既是 mask 参数
  % 又是内部块的固有参数，InlineMasks 展开后必须保留）不跳——H 类 7 回归教训
  isMaskedBlk = false; maskNms = {};
  try
    if strcmp(get_param(b, 'Mask'), 'on') && isempty(get_param(b, 'ReferenceBlock'))
      isMaskedBlk = true;
      maskNms = get_param(b, 'MaskNames');
      if ~iscell(maskNms), maskNms = {}; end
    end
  catch
  end
  skip = {'Position','Name','Ports','CompiledPortDataTypes','ReferenceBlock', ...
          'AttributesFormatString','LinkStatus','Script', ...
          'ErrorFcn','TemplateBlock','MemberBlocks','BlockChoice', ...
          'Variant','VariantChoicesSpecifier','VariantChoicesEnumeration','VariantControlVariable', ...
          'VariantControlMode','VariantControl','LabelModeActiveChoice','VariantActivationTime', ...
          'AllowZeroVariantControls','PropagateVariantConditions','AllowFlexibleInterface', ...
          'TreatAsGroupedWhenPropagatingVariantConditions','ReferencedSubsystem','Latency', ...
          'AutoFrameSizeCalculation','TreatAsAtomicUnit','PermitHierarchicalResolution','Permissions', ...
          'ShowSubsystemReinitializePorts','MinAlgLoopOccurrences','ScheduleAs','PartitionName', ...
          'SetExecutionDomain','ExecutionDomainType','RTWSystemCode','RTWFcnNameOpts','RTWFcnName', ...
          'RTWFileNameOpts','RTWFileName','FunctionInterfaceSpec','FunctionWithSeparateData', ...
          'RTWMemSecFuncInitTerm','RTWMemSecFuncExecute','RTWMemSecDataConstants', ...
          'RTWMemSecDataInternal','RTWMemSecDataParameters', ...
          'ParameterArgumentNames','ParameterArgumentValues', ...
          'ModelNameDialog','ModelNamePreexists','ModelNameSpecified', ...
          'CachedPortDiscreteRates','CachedModelReference','PortsSpecInport', ...
          'ModelReferenceRefState'};
  for j = 1:numel(names)
    nm = names{j};
    if any(strcmp(nm, skip)), continue; end
    % masked 块：mask 参数（Kp/Ki 一类）由 emit_mask_create 重建，
    % 不能走 set_param——无 mask 容器报"没有为该名的参数"（H 类 7 修复）
    if isMaskedBlk && any(strcmp(nm, maskNms)), continue; end
    % 库链接实例的"链接保护"参数：add_block 对链接模块拒绝应用（R2026a
    % 实测 RestrictArgs 报"无法更改…链接模块"；R2023b/2025a 根本不把
    % 它暴露进 DialogParameters，跳过对旧版本无影响）。实例值与库默认
    % 一致（库提供），跳过无损；重建件再导出走同一 emit 逻辑，二次
    % 快照比对不受影响。
    try, rbP = get_param(b, 'ReferenceBlock'); catch, rbP = ''; end
    if ischar(rbP) && ~isempty(rbP) && any(strcmp(nm, {'RestrictArgs'})), continue; end
    try
      at = dps.(nm).Attributes;
      if (iscell(at) && any(strcmp('read-only', at))) || (ischar(at) && contains(at, 'read-only'))
        continue;
      end
    catch
    end
    try
      v = get_param(b, nm);
      if ischar(v) || isnumeric(v) || islogical(v)
        if ischar(v) && numel(v) > 4000, continue; end
        % 本地化枚举显示名（如中文 Scope TimeSpan='自动'）不写：见函数注释
        if ischar(v) && is_locale_default(b, nm, v), continue; end
        fprintf(fid, ', ''%s'', %s', nm, mval(v));
      end
    catch
    end
  end
  try
    sc = get_param(b, 'Script');
    if ischar(sc) && ~isempty(sc)
      fprintf(fid, ', ''Script'', %s', mval(sc));
    end
  catch
  end
end

%% ---------- 参数值的可移植性判断 + 内置块库路径 ----------
function tf = is_locale_default(b, nm, v)
% 该参数值是否"等于同类块新建时的默认值"，且值里含非 ASCII 字符。
%
% 为什么必须这样处理：内置/mask 块的枚举显示名随 MATLAB 语言本地化，
% get_param 返回本地化字符串（R2023b 中文环境里 Scope 的 TimeSpan 读作
% '自动'）。把它原样写进快照，换版本/语言就 set 不回去——R2026a 的
% add_block 只认 'Auto'，中文值报 "'TimeSpan' 参数的值 '自动' 无效"。
% 省略则各版本各自用自身默认，语义等价、跨版本可跑。
% 实测依据：8 个模型 255 个 Scope 的 TimeSpan 全部等于默认值（probe_enum3）。
% 只对含非 ASCII 的值生效——ASCII 值跨语言安全，且默认值比对不该扩大范围
% （MaskDescription 这类自由文本必须照写）。
tf = false;
if ~ischar(v) || isempty(v) || ~any(double(v) > 127), return; end
bt = '';
try, bt = get_param(b, 'BlockType'); catch, return; end
d = block_default_value(bt, nm);
tf = ~isempty(d) && strcmp(d, v);
end

function d = block_default_value(bt, nm)
% 同类块新建时的默认值（按 BlockType+参数名缓存；取不到返回 ''）
persistent cache
if isempty(cache), cache = struct(); end
fld = matlab.lang.makeValidName([bt '_' nm]);
if isfield(cache, fld), d = cache.(fld); return; end
d = '';
src = snp_block_source(bt);
if ~isempty(src)
  probeM = 'snp_paramprobe';
  try
    if bdIsLoaded(probeM), close_system(probeM, 0); end
    new_system(probeM);
    add_block(src, [probeM '/p']);
    d = get_param([probeM '/p'], nm);
    close_system(probeM, 0);
  catch
    d = '';
    try, if bdIsLoaded(probeM), close_system(probeM, 0); end, catch, end
  end
end
cache.(fld) = d;
end


%% ---------- library instance -> module name (three tiers) ----------
function mod = libmod_of(b, libNames, aliasMap)
  mod = '';
  try   % ① FP_* fingerprint annotation inside the subsystem
    anns = find_system(b, 'FindAll', 'on', 'LookUnderMasks', 'all', 'SearchDepth', 1, 'Type', 'annotation');
    for i = 1:numel(anns)
      t = get_param(anns(i), 'Name');
      if startsWith(t, 'FP_')
        tok = extractBetween(t, 'FP_', '_v');
        if ~isempty(tok), mod = tok{1}; return; end
      end
    end
  catch
  end
  nm = get_param(b, 'Name');           % ② block name (trailing digits stripped) vs lib list
  base = regexprep(nm, '\d+$', '');
  if any(strcmp(libNames, nm)), mod = nm; return; end
  if any(strcmp(libNames, base)), mod = base; return; end
  if ~isempty(aliasMap)                % ③ user alias table
    ai = find(strcmp(aliasMap(:,1), nm) | strcmp(aliasMap(:,1), base), 1);
    if ~isempty(ai), mod = aliasMap{ai,2}; end
  end
end

%% ---------- 独立 Stateflow chart 检测（EMChart 不会误命中：MATLAB Function 是另一类）----------
function ch = chart_of(b)
  ch = [];
  try
    rt = sfroot;                       % 不能链式 sfroot().find()：-batch 下抛"不支持函数调用语法"（T63）
    ch = rt.find('-isa', 'Stateflow.Chart', '-and', 'Path', b);
  catch err
    fprintf(2, '[snp] chart 检测失败，%s 将按普通子系统导出：%s\n', b, err.message);
  end
end

%% ---------- chart 结构化导出（T42/T44）----------
%  chart 无 Script 属性（区别于 MATLAB Function 的 EMChart），内容是图形化
%  状态机。逐个导出 State（Name/LabelString）与 Transition（Source/Destination/
%  LabelString），重建时用 Stateflow.State/Transition 对象。
%  关键写法（实测验证，probe_chart_rebuild）：LabelString 的换行在快照里写字面
%  \n，重建代码必须用 sprintf('...') 包裹——单引号字面 \n 不会被还原成真换行，
%  Stateflow 会把字面反斜杠解析进状态名（T28 同源坑）。
%  State 的 Name 可能含 \n 解析残留，取首行干净名。空标签的转移 Stateflow 会
%  自动填 '?'，重建时写空串（回读时 '?' 视为等价空）。
function emit_chart_content(fid, ch, rel)
  sts = ch.find('-isa', 'Stateflow.State');
  trs = ch.find('-isa', 'Stateflow.Transition');
  u = ['ch' regexprep(rel, '[^A-Za-z0-9_]', '')];  % 确定性前缀：随机前缀让逐字节新鲜度比对永远 stale
  fprintf(fid, '  %% ---- chart %s 内容（Stateflow 结构化导出）----\n', rel);
  fprintf(fid, '  %s_rt = sfroot();\n', u);
  fprintf(fid, '  %s_ch = %s_rt.find(''-isa'', ''Stateflow.Chart'', ''-and'', ''Path'', [m ''/%s'']); %s_ch = %s_ch(1);\n', u, u, rel, u, u);
  names = {};
  for i = 1:numel(sts)
    s = sts(i);
    nm = regexp(s.Name, '^[^\n]+', 'match');
    if isempty(nm), nm = {s.Name}; end
    nm = strtrim(nm{1});
    names{end+1} = nm; %#ok<AGROW>
    lbl = strrep(s.LabelString, sprintf('\n'), '\n');
    fprintf(fid, '  %s_s%d = Stateflow.State(%s_ch); %s_s%d.Name = ''%s''; %s_s%d.LabelString = sprintf(''%s'');\n', ...
      u, i, u, u, i, nm, u, i, lbl);
  end
  for i = 1:numel(trs)
    t = trs(i);
    srcIdx = 0; dstIdx = 0;
    if ~isempty(t.Source)
      nmS = regexp(t.Source.Name, '^[^\n]+', 'match');
      if isempty(nmS), nmS = {t.Source.Name}; end
      srcIdx = find(strcmp(names, strtrim(nmS{1})), 1);
    end
    if ~isempty(t.Destination)
      nmD = regexp(t.Destination.Name, '^[^\n]+', 'match');
      if isempty(nmD), nmD = {t.Destination.Name}; end
      dstIdx = find(strcmp(names, strtrim(nmD{1})), 1);
    end
    lbl = strrep(t.LabelString, sprintf('\n'), '\n');
    if strcmp(lbl, '?'), lbl = ''; end
    if srcIdx == 0 && dstIdx > 0
      % 默认转移（Source 为空）：只设 Destination
      fprintf(fid, '  %s_t%d = Stateflow.Transition(%s_ch); %s_t%d.Destination = %s_s%d; %s_t%d.LabelString = sprintf(''%s'');\n', ...
        u, i, u, u, i, u, dstIdx, u, i, lbl);
    elseif srcIdx > 0 && dstIdx > 0
      fprintf(fid, '  %s_t%d = Stateflow.Transition(%s_ch); %s_t%d.Source = %s_s%d; %s_t%d.Destination = %s_s%d; %s_t%d.LabelString = sprintf(''%s'');\n', ...
        u, i, u, u, i, u, srcIdx, u, i, u, dstIdx, u, i, lbl);
    end
    % src 与 dst 都为 0（孤立转移）：跳过——重建无意义且不会命中
  end
  % 收尾标记：snp_pull 的块附属行组以此为边界（否则 chart 内容行不随块回流）
  fprintf(fid, '  %% ---- chart %s end ----\n', rel);
end

