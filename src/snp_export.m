  end
end

%% ---------- 裸 masked SubSystem 的内部块补导出（H 类 7 配套）----------
%  LookUnderMasks='none' 的主枚举列不到 masked 子系统内部块；裸 masked 容器
%  重建后是空的，补导出直接子级。端口块（In1/Out1）由容器自生跳过（T39 同源）。
%  语义与 masked 副本路径（L807 起）一致，仅作用于无 rb 的裸 masked SubSystem。
function [libsNeeded, libFiles] = emit_inner_bare_masked(fid, b, rel, mdl, libNames, opts, libsNeeded, libFiles)
  inner = find_system(b, 'LookUnderMasks', 'all', 'SearchDepth', 1, 'Type', 'block');
  inner = setdiff(inner, b);
  for k = 1:numel(inner)
    ib = inner{k};
    irel = strrep(ib, [b '/'], '');
    bt2 = get_param(ib, 'BlockType');
    if any(strcmp(bt2, {'Inport', 'Outport'})), continue; end
    try, rb2 = get_param(ib, 'ReferenceBlock'); catch, rb2 = ''; end
    src2 = rb2;
    isMf2 = false;
    if isempty(src2)
      src2 = snp_block_source(bt2);
      if isempty(src2) && strcmp(bt2, 'SubSystem')
        [libsNeeded, libFiles] = expand_masked(fid, ib, [rel '/' irel], mdl, ...
          libNames, opts, libsNeeded, libFiles);
        continue;
      end
      sc0 = get_chart_script(ib);
      if isempty(src2) && ~isempty(sc0)
        src2 = 'simulink/User-Defined Functions/MATLAB Function';
        isMf2 = true;
      end
      if isempty(src2) && strcmp(bt2, 'S-Function') && isempty(sc0)
        src2 = 'simulink/User-Defined Functions/S-Function';
      end
      if isempty(src2) && ~isempty(chart_of(ib))
        src2 = 'sflib/Chart';
      end
      if isempty(src2) && strcmp(bt2, 'SubSystem')
        src2 = 'built-in/SubSystem';
      end
    end
    if isempty(src2)
      fprintf(2, '[snp_export skip inner] %s/%s (BlockType=%s)\n', rel, irel, bt2);
      continue;
    end
    fprintf(fid, '  add_block(%s, [m ''/%s/%s''], ''Position'', %s', ...
      msrc(src2), rel, irel, mat2str(get_param(ib, 'Position')));
    emit_block_params(fid, ib);
    fprintf(fid, ');\n');
    if isMf2
      fprintf(fid, '  rtc = get_param(m, ''Object'').find(''-isa'', ''Stateflow.EMChart'', ''-and'', ''Path'', [m ''/%s/%s'']);\n', rel, irel);
      fprintf(fid, '  rtc.Script = strjoin(%s, sprintf(''\\n''));\n', mval_lines(sc0));
      emit_chart_restore(fid, ib, [rel '/' irel], sc0);
    end
    chObj2 = chart_of(ib);
    if ~isempty(chObj2)
      emit_chart_content(fid, chObj2, [rel '/' irel]);
    end
  end
  % 内部块之间的连线（只取直接子级之间，与 masked 副本路径同规则）
  innerLines = find_system(b, 'FindAll', 'on', 'LookUnderMasks', 'all', ...
    'SearchDepth', 1, 'Type', 'line');
  nameOf = @(h) get_param(get_param(h, 'SrcPortHandle'), 'Parent');
  for k = 1:numel(innerLines)
    try
      lh = innerLines(k);
      sp = get_param(lh, 'SrcPortHandle'); dp = get_param(lh, 'DstPortHandle');
      sb = get_param(get_param(sp, 'Parent'), 'Name');
      db = get_param(get_param(dp, 'Parent'), 'Name');
      spn = get_param(sp, 'PortNumber'); dpn = get_param(dp, 'PortNumber');
      fprintf(fid, '  add_line(m, ''%s/%s|%d'', ''%s/%s|%d'', ''autorouting'', ''on'');\n', ...
        rel, sb, spn, rel, db, dpn);
    catch
    end
  end
end

%% ---------- 裸 masked SubSystem 的 mask 新建（H 矩阵类 7 缺口修复）----------
%  无库链接的 masked 子系统在 M 线是 built-in/SubSystem 空容器——mask 必须用
%  Simulink.Mask.create + addParameter 重建（构造时内带 Value；R2023b 实测
%  set_param 'MaskPrompts' 不能为无 mask 容器凭空造参数）。只用于裸容器；
%  库副本路径（mask 已由库侧建好）仍走 replay_mask。
function emit_mask_create(fid, b, rel)
  u = sprintf('mk%d', round(rand() * 1e9));
  fprintf(fid, '  %s = Simulink.Mask.create([m ''/%s'']);\n', u, rel);
  nms = {}; vals = {}; tys = {}; prms = {};
  try, nms = get_param(b, 'MaskNames'); catch, end
  try, vals = get_param(b, 'MaskValues'); catch, end
  try, tys = get_param(b, 'MaskTypeStrings'); catch, end
  try, prms = get_param(b, 'MaskPrompts'); catch, end
  if isempty(nms), return; end
  if isempty(vals), vals = cell(1, numel(nms)); end
  if isempty(tys), tys = cell(1, numel(nms)); end
  if isempty(prms), prms = cell(1, numel(nms)); end
  for i = 1:numel(nms)
    pv = nms{i};
    if i <= numel(prms) && ~isempty(prms{i}), pv = prms{i}; end
    vv = '';
    if i <= numel(vals) && ~isempty(vals{i}), vv = vals{i}; end
    % addParameter 只带 Name/Value/Prompt（'Type' 参数名/值在 R2023b 与
    % MaskTypeStrings 不一致，实测报"无法识别的形式"——默认 edit 类型）
    fprintf(fid, '  %s.addParameter(''Name'', %s, ''Value'', %s, ''Prompt'', %s);\n', ...
      u, mval(nms{i}), mval(vv), mval(pv));
  end
  % 展示类属性（标题/描述/颜色）
  maskAttrs = {'MaskType','MaskDescription','MaskDisplay','MaskVariables', ...
    'MaskStyleString','BackgroundColor','ForegroundColor'};
  for i = 1:numel(maskAttrs)
    try
      v = get_param(b, maskAttrs{i});
      if ischar(v) && ~isempty(v)
        fprintf(fid, '  set_param([m ''/%s''], ''%s'', %s);\n', rel, maskAttrs{i}, mval(v));
      end
    catch
    end
  end
end

%% ---------- mask 属性重放（只有原本 masked 的块才重建 mask）----------
function replay_mask(fid, srcPath, destRel)
  isMaskedSub = false;
  try, isMaskedSub = strcmp(get_param(srcPath, 'Mask'), 'on'); catch, end
  if ~isMaskedSub, return; end
  fprintf(fid, '  set_param([m ''/%s''], ''Mask'', ''on'');\n', destRel);
  maskAttrs = {'MaskType','MaskDescription','MaskDisplay','MaskVariables', ...
    'MaskStyleString','BackgroundColor','ForegroundColor'};
  for i = 1:numel(maskAttrs)
    try
      v = get_param(srcPath, maskAttrs{i});
      if ischar(v) && ~isempty(v)
        fprintf(fid, '  set_param([m ''/%s''], ''%s'', %s);\n', destRel, maskAttrs{i}, mval(v));
      end
    catch
    end
  end
  for nm = {'MaskPrompts','MaskValues'}
    try
      v = get_param(srcPath, nm{1});
      if iscell(v)
        if isempty(v)
          fprintf(fid, '  set_param([m ''/%s''], ''%s'', {});\n', destRel, nm{1});
        else
          parts = cellfun(@mval, v(:)', 'UniformOutput', false);
          fprintf(fid, '  set_param([m ''/%s''], ''%s'', {%s});\n', destRel, nm{1}, strjoin(parts, ', '));
        end
      end
    catch
    end
  end
end

%% ---------- masked 子系统展开导出（内部结构 + mask 属性重放）----------
%  为什么需要：库模型自身就是 masked 子系统（顶层块 Mask='on'）。若不展开，
%  "改子系统内部" 就无法落到代码上——这正是"子系统要单独一份代码"的实现点。
function [libsNeeded, libFiles] = expand_masked(fid, maskedPath, destRel, mdl, libNames, opts, libsNeeded, libFiles)
  % 该块自带 Stateflow chart（忠实化模型里的 SMO/LDO/DSO 观察器——masked 的
  % MATLAB Function 块）→ 按 MATLAB Function 导出并回灌 Script，**不展开内部**：
  % 内部 ' SFunction ' 只是 Stateflow 运行时块（端口由 Script 签名决定），
  % 展开后端口全错，外部按 'X/N' 引用即报"Simulink 对象名称无效"。
  scOwn = get_chart_script(maskedPath);
  if ~isempty(scOwn)
    % 块参数（SystemSampleTime 等）必须随 add_block 一并写入——观测器块靠
    % 它锁离散采样；缺了它继承连续采样，persistent 变量即报"无效的构造"。
    btOwn = get_param(maskedPath, 'BlockType');
fprintf(fid, '  add_block(''simulink/User-Defined Functions/MATLAB Function'', [m ''/%s''], ''Position'', %s', ...
      destRel, mat2str(get_param(maskedPath, 'Position')));
    emit_block_params(fid, maskedPath);
    fprintf(fid, ');\n');
    fprintf(fid, '  rtc = get_param(m, ''Object'').find(''-isa'', ''Stateflow.EMChart'', ''-and'', ''Path'', [m ''/%s'']);\n', destRel);
    fprintf(fid, '  rtc.Script = strjoin(%s, sprintf(''\\n''));\n', mval_lines(scOwn));
    emit_chart_restore(fid, maskedPath, destRel, scOwn);
    replay_mask(fid, maskedPath, destRel);
    return;
  end
fprintf(fid, '  add_block(''built-in/Subsystem'', [m ''/%s''], ''Position'', %s);\n', ...
    destRel, mat2str(get_param(maskedPath, 'Position')));
  isVar = false;
  try, isVar = strcmp(get_param(maskedPath, 'Variant'), 'on'); catch, end
  if isVar
    % 变体子系统：**只导出当前激活分支**，且不重建容器自身的自动端口
    % （In1/Out1 由 Simulink 按分支重生成）。变体切换机制无法用文本表达，
    % 这是刻意的能力边界（README「保真与边界」一节同述）。
    fprintf(2, '[snp_export note] 变体子系统 %s 按当前激活分支展开（变体切换机制不保留）\n', destRel);
    replay_mask(fid, maskedPath, destRel);
    varBranches = find_system(maskedPath, 'LookUnderMasks', 'all', 'SearchDepth', 1, ...
      'MatchFilter', @Simulink.match.activeVariants, 'BlockType', 'SubSystem');
    varBranches = setdiff(varBranches, {maskedPath});
    for k = 1:numel(varBranches)
      brel = strrep(varBranches{k}, [maskedPath '/'], '');
      % 跳过 Simulink 为分支自动建的空白壳（Subsystem/Subsystem1…，无内部块）
      kids = find_system(varBranches{k}, 'LookUnderMasks', 'all', 'SearchDepth', 1, 'Type', 'block');
      if isempty(setdiff(kids, {varBranches{k}}))
        continue;
      end
      [libsNeeded, libFiles] = expand_masked(fid, varBranches{k}, [destRel '/' brel], mdl, ...
        libNames, opts, libsNeeded, libFiles);
    end
    return;
  end
  replay_mask(fid, maskedPath, destRel);
  % 内部块（**只取直接子级**：SearchDepth=1。更深一层须经递归展开——
  % LookUnderMasks=all + SearchDepth=2 会钻进库链接实例（如 PLL 里的 pd）的
  % mask 内部，把其内部块也列出来，导致 add_block 重复添加报"无法添加名为 …"
  inner = find_system(maskedPath, 'LookUnderMasks', 'all', 'SearchDepth', 1, 'Type', 'block');
  inner = setdiff(inner, maskedPath);
  for k = 1:numel(inner)
    ib = inner{k};
    irel = strrep(ib, [maskedPath '/'], '');
    bt = get_param(ib, 'BlockType');
    % 变体容器的自动端口块（In1/Out1…）会与 built-in/Subsystem 自建的端口同名冲突；
    % 重建后由 Simulink 按分支子系统的端口自动生成，跳过原件里的这些自动块。
    if isVar && any(strcmp(bt, {'Inport','Outport'})) && isauto_variant_port(ib, maskedPath)
      continue;
    end
    try, rb = get_param(ib, 'ReferenceBlock'); catch, rb = ''; end
    src = rb;
    isMf = false;
    if isempty(src)
      src = snp_block_source(bt);
      if isempty(src) && strcmp(bt, 'SubSystem')
        % 无库链接的内部子系统（masked 断链副本 / 普通子系统）→ 递归展开
        [libsNeeded, libFiles] = expand_masked(fid, ib, [destRel '/' irel], mdl, ...
          libNames, opts, libsNeeded, libFiles);
        continue;
      end
      if isempty(src)
        % MATLAB Function 块（BlockType 显示 S-Function、FunctionName=sf_sfun，
        % 内部是 Stateflow chart）：端口由 Script 签名决定，必须建 MATLAB
        % Function 并回灌 Script——建成通用 S-Function 会只剩 1 入 1 出，
        % 外部按 'X/N' 引用端口即报"对象名称无效"
        sc0 = get_chart_script(ib);
        if ~isempty(sc0)
          src = 'simulink/User-Defined Functions/MATLAB Function';
          isMf = true;
        elseif strcmp(bt, 'S-Function')
          % 真 S-Function（自定义 .m 实现）：与顶层同规则
          src = 'simulink/User-Defined Functions/S-Function';
        end
      end
    end
    if isempty(src)
      fprintf(2, '[snp_export skip inner] %s/%s (BlockType=%s)\n', destRel, irel, bt);
      continue;
    end
    if isMf
fprintf(fid, '  add_block(%s, [m ''/%s/%s''], ''Position'', %s);\n', ...
        msrc(src), destRel, irel, mat2str(get_param(ib, 'Position')));
      fprintf(fid, '  rtc = get_param(m, ''Object'').find(''-isa'', ''Stateflow.EMChart'', ''-and'', ''Path'', [m ''/%s/%s'']);\n', destRel, irel);
      fprintf(fid, '  rtc.Script = strjoin(%s, sprintf(''\\n''));\n', mval_lines(get_chart_script(ib)));
      emit_chart_restore(fid, ib, [destRel '/' irel], get_chart_script(ib));
      continue;
    end
    if strcmp(bt, 'Inport') || strcmp(bt, 'Outport')
      % 库块 In1/Out1 不接受 block-specific 参数（EventTriggers 等）——只给端口号。
      % 注意 get_param('Port') 返回**字符**（'1'），直接塞进 %d 会按字符码变成 49
      % ——端口号全被偏移，父级连线引用 'X/1' 即报端口无效。必须 str2double。
      pnum = str2double(get_param(ib, 'Port'));
      if isnan(pnum) || pnum < 1, pnum = 1; end
fprintf(fid, '  add_block(%s, [m ''/%s/%s''], ''Position'', %s, ''Port'', ''%d'');\n', ...
        msrc(src), destRel, irel, mat2str(get_param(ib, 'Position')), pnum);
      continue;
    end
fprintf(fid, '  add_block(%s, [m ''/%s/%s''], ''Position'', %s', ...
      msrc(src), destRel, irel, mat2str(get_param(ib, 'Position')));
    emit_block_params(fid, ib);
    fprintf(fid, ');\n');
    sc = get_chart_script(ib);
    if ~isempty(sc)
      fprintf(fid, '  rtc = get_param(m, ''Object'').find(''-isa'', ''Stateflow.EMChart'', ''-and'', ''Path'', [m ''/%s/%s'']);\n', destRel, irel);
      fprintf(fid, '  rtc.Script = strjoin(%s, sprintf(''\\n''));\n', mval_lines(sc));
      emit_chart_restore(fid, ib, [destRel '/' irel], sc);
    end
  end
  % 内部线（**只取直接子级之间的线**：SearchDepth=1——SearchDepth=2 会取到
  % 钻进库链接实例内部的线，add_line 引用其内部块名即"Simulink 对象名称
  % 无效"。按 源块/源端口/目标块/目标端口 去重——分支在 Simulink 里是一条线
  % 多 dst，若按线枚举会重复连同一端口，触发"目标端口已有信号线连接"）
  lines = find_system(maskedPath, 'FindAll', 'on', 'LookUnderMasks', 'all', ...
    'SearchDepth', 1, 'Type', 'line');
  seen = {};
  for k = 1:numel(lines)
    try
      srcH = get_param(lines(k), 'SrcPortHandle');
      if srcH <= 0, continue; end
      try
        if strcmp(get_param(srcH, 'PortType'), 'connection'), continue; end
      catch
      end
      dstH = get_param(lines(k), 'DstPortHandle');
      dstH = dstH(dstH > 0);
      if isempty(dstH), continue; end
      sName = get_param(get_param(lines(k), 'SrcBlockHandle'), 'Name');
      sPort = get_param(srcH, 'PortNumber');
      for q = 1:numel(dstH)
        dName = get_param(get_param(dstH(q), 'Parent'), 'Name');
        dPort = get_param(dstH(q), 'PortNumber');
        key = sprintf('%s/%d>%s/%d', sName, sPort, dName, dPort);
        if any(strcmp(seen, key)), continue; end
        seen{end+1} = key; %#ok<AGROW>
        fprintf(fid, '  add_line([m ''/%s''], ''%s/%d'', ''%s/%d'', ''autorouting'', ''off'');\n', ...
          destRel, sName, sPort, dName, dPort);
      end
    catch
    end
  end
  % 库实例内部的物理（Simscape）连接
  cons = snp_phys_connections(maskedPath);
  for i = 1:numel(cons)
    net = cons{i};
    for q = 2:numel(net)
      fprintf(fid, '  add_line([m ''/%s''], ''%s'', ''%s'');\n', destRel, net{1}, net{q});
    end
  end
end

